CREATE OR REPLACE FUNCTION fn_setting(p_key VARCHAR2) RETURN NUMBER IS
  v NUMBER;
BEGIN
  SELECT setting_value INTO v FROM rd_settings WHERE setting_key = p_key;
  RETURN v;
END;
