-- استبدال نقاط بمكافأة
CREATE OR REPLACE PROCEDURE sp_redeem_reward(
  p_user_id   IN  NUMBER,
  p_reward_id IN  NUMBER,
  p_code      OUT VARCHAR2
) IS
  v_cost  NUMBER;
  v_pts   NUMBER;
  v_title VARCHAR2(100);
BEGIN
  SELECT cost_points, title INTO v_cost, v_title FROM rd_rewards WHERE reward_id = p_reward_id;
  SELECT loyalty_points INTO v_pts FROM rd_users WHERE user_id = p_user_id FOR UPDATE;

  IF v_pts < v_cost THEN
    RAISE_APPLICATION_ERROR(-20020, 'رصيد النقاط غير كافٍ');
  END IF;

  p_code := 'RW-' || TO_CHAR(TRUNC(DBMS_RANDOM.VALUE(10000, 99999)));
  UPDATE rd_users SET loyalty_points = loyalty_points - v_cost WHERE user_id = p_user_id;
  INSERT INTO rd_redemptions (user_id, reward_id, voucher_code) VALUES (p_user_id, p_reward_id, p_code);
  INSERT INTO rd_loyalty_rewards (user_id, action_type, points, reward_description)
  VALUES (p_user_id, 'REDEEM', -v_cost, v_title || ' (' || p_code || ')');
  COMMIT;
END;
