-- الإدارة: تعديل نسب العمولة (0 إلى 50)
CREATE OR REPLACE PROCEDURE sp_set_commission(p_booking_pct IN NUMBER, p_meal_pct IN NUMBER) IS
BEGIN
  IF p_booking_pct NOT BETWEEN 0 AND 50 OR p_meal_pct NOT BETWEEN 0 AND 50 THEN
    RAISE_APPLICATION_ERROR(-20040, 'النسبة يجب أن تكون بين 0 و 50');
  END IF;
  UPDATE rd_settings SET setting_value = p_booking_pct WHERE setting_key = 'BOOKING_COMMISSION_PCT';
  UPDATE rd_settings SET setting_value = p_meal_pct    WHERE setting_key = 'MEAL_COMMISSION_PCT';
  COMMIT;
END;
/

-- الإدارة: حالة الزحام وإظهار/إخفاء المحطة
CREATE OR REPLACE PROCEDURE sp_set_station_load(p_station_id IN NUMBER, p_load_pct IN NUMBER) IS
  v_pct NUMBER := LEAST(100, GREATEST(0, p_load_pct));
BEGIN
  UPDATE rd_rest_stops
     SET occupancy_percentage = v_pct,
         congestion_level = CASE WHEN v_pct < 40 THEN 'LOW' WHEN v_pct < 75 THEN 'MEDIUM' ELSE 'HIGH' END
   WHERE rest_stop_id = p_station_id;
  COMMIT;
END;
