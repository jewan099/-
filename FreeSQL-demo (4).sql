-- الوجبات
CREATE TABLE rd_meals (
  meal_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  meal_name       VARCHAR2(100) NOT NULL,
  price           NUMBER(10,2)  NOT NULL CHECK (price > 0),
  is_active       NUMBER(1)     DEFAULT 1 NOT NULL CHECK (is_active IN (0,1))
);

-- طلبات الوجبات من أصحاب الحملات
CREATE TABLE rd_meal_orders (
  order_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_code      VARCHAR2(20) NOT NULL UNIQUE,
  campaign_id     NUMBER NOT NULL REFERENCES rd_users(user_id),
  rest_stop_id    NUMBER NOT NULL REFERENCES rd_rest_stops(rest_stop_id),
  meal_id         NUMBER REFERENCES rd_meals(meal_id),   -- قد يكون NULL لوجبة قديمة محذوفة
  meal_name       VARCHAR2(100) NOT NULL,                -- نسخة من الاسم وقت الطلب
  quantity        NUMBER(5)     NOT NULL CHECK (quantity > 0),
  total           NUMBER(12,2)  NOT NULL,
  status          VARCHAR2(10)  DEFAULT 'PAID' NOT NULL
                  CHECK (status IN ('PAID','PREPARING','DELIVERED')),
  created_at      DATE          DEFAULT SYSDATE NOT NULL
);

-- المحافظ وسجل حركاتها
CREATE TABLE rd_wallets (
  user_id         NUMBER PRIMARY KEY REFERENCES rd_users(user_id),
  balance         NUMBER(12,2) DEFAULT 0 NOT NULL CHECK (balance >= 0)
);

CREATE TABLE rd_wallet_ledger (
  entry_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id         NUMBER NOT NULL REFERENCES rd_users(user_id),
  amount          NUMBER(12,2) NOT NULL,           -- موجب = إيداع، سالب = خصم
  reason          VARCHAR2(200) NOT NULL,
  ref_code        VARCHAR2(30),
  created_at      DATE DEFAULT SYSDATE NOT NULL
);

-- المكافآت واستبدال النقاط
CREATE TABLE rd_rewards (
  reward_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title           VARCHAR2(100) NOT NULL,
  cost_points     NUMBER(6)     NOT NULL CHECK (cost_points > 0)
);

CREATE TABLE rd_redemptions (
  redemption_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id         NUMBER NOT NULL REFERENCES rd_users(user_id),
  reward_id       NUMBER NOT NULL REFERENCES rd_rewards(reward_id),
  voucher_code    VARCHAR2(20) NOT NULL UNIQUE,
  created_at      DATE DEFAULT SYSDATE NOT NULL
);

-- طلبات التحويل البنكي لأصحاب المحطات
CREATE TABLE rd_payouts (
  payout_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payout_code     VARCHAR2(20) NOT NULL UNIQUE,
  rest_stop_id    NUMBER NOT NULL REFERENCES rd_rest_stops(rest_stop_id),
  amount          NUMBER(12,2) NOT NULL CHECK (amount > 0),
  status          VARCHAR2(10) DEFAULT 'PENDING' NOT NULL CHECK (status IN ('PENDING','PAID')),
  created_at      DATE DEFAULT SYSDATE NOT NULL
);

CREATE INDEX ix_rd_orders_station  ON rd_meal_orders(rest_stop_id);
CREATE INDEX ix_rd_orders_campaign ON rd_meal_orders(campaign_id);
CREATE INDEX ix_rd_bookings_stop   ON rd_bookings(rest_stop_id);
CREATE INDEX ix_rd_reviews_stop    ON rd_reviews(rest_stop_id);

