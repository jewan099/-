-- تأكيد حجز: يضيف نقاط الحجز (50) للمستخدم ويسجّلها في سجل الولاء
CREATE OR REPLACE PROCEDURE sp_confirm_booking(
  p_user_id         IN  NUMBER,
  p_station_id      IN  NUMBER,
  p_booking_type_id IN  NUMBER,
  p_arrival_time    IN  VARCHAR2,
  p_people          IN  NUMBER,
  p_code            OUT VARCHAR2
) IS
  v_price NUMBER;
  v_fee   NUMBER;
  v_pts   NUMBER := fn_setting('POINTS_PER_BOOKING');
BEGIN
  -- النوع المطلوب يجب أن تكون المحطة توفّر خدمته
  BEGIN
    SELECT bt.price INTO v_price
      FROM rd_booking_types bt
      JOIN rd_rest_stop_services ss ON ss.service_id = bt.service_id
      JOIN rd_rest_stops s          ON s.rest_stop_id = ss.rest_stop_id
     WHERE bt.booking_type_id = p_booking_type_id
       AND ss.rest_stop_id = p_station_id
       AND s.is_visible = 1;
  EXCEPTION WHEN NO_DATA_FOUND THEN
    RAISE_APPLICATION_ERROR(-20001, 'هذه الخدمة غير متوفرة في المحطة المختارة');
  END;

  v_fee  := ROUND(v_price * fn_setting('BOOKING_COMMISSION_PCT') / 100, 2);
  p_code := 'RD-' || TO_CHAR(TRUNC(DBMS_RANDOM.VALUE(10000, 99999)));

  INSERT INTO rd_bookings (booking_code, rest_stop_id, driver_id, booking_type_id, price, arrival_time,
                           people_count, booking_date, status, total_amount, platform_fee, net_owner_amount)
  VALUES (p_code, p_station_id, p_user_id, p_booking_type_id, v_price, p_arrival_time,
          NVL(p_people, 1), TRUNC(SYSDATE), 'confirmed', v_price, v_fee, v_price - v_fee);

  IF p_user_id IS NOT NULL THEN
    UPDATE rd_users SET loyalty_points = loyalty_points + v_pts WHERE user_id = p_user_id;
    INSERT INTO rd_loyalty_rewards (user_id, action_type, points, reward_description)
    VALUES (p_user_id, 'BOOKING', v_pts, 'تأكيد حجز ' || p_code);
  END IF;
  COMMIT;
END;
/

-- إضافة تقييم وتعليق: يضيف نقاط التقييم (10)
CREATE OR REPLACE PROCEDURE sp_add_review(
  p_user_id    IN NUMBER,
  p_station_id IN NUMBER,
  p_name       IN VARCHAR2,
  p_rating     IN NUMBER,
  p_comment    IN VARCHAR2
) IS
  v_pts NUMBER := fn_setting('POINTS_PER_REVIEW');
BEGIN
  IF p_comment IS NULL OR LENGTH(TRIM(p_comment)) = 0 THEN
    RAISE_APPLICATION_ERROR(-20010, 'اكتب تعليقك أولًا');
  END IF;

  INSERT INTO rd_reviews (rest_stop_id, driver_id, reviewer_name, rating, comment_text)
  VALUES (p_station_id, p_user_id, NVL(TRIM(p_name), 'ضيف راحة'), p_rating, SUBSTR(p_comment, 1, 300));

  IF p_user_id IS NOT NULL THEN
    UPDATE rd_users SET loyalty_points = loyalty_points + v_pts WHERE user_id = p_user_id;
    INSERT INTO rd_loyalty_rewards (user_id, action_type, points, reward_description)
    VALUES (p_user_id, 'REVIEW', v_pts, 'إضافة تقييم للمحطة رقم ' || p_station_id);
  END IF;
  COMMIT;
END;
