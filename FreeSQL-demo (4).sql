-- 0. حذف الجداول الجديدة إن كانت موجودة من تشغيل سابق (يجعل السكربت قابلًا للإعادة)
--------------------------------------------------------------------------------
DECLARE
  TYPE t_list IS TABLE OF VARCHAR2(40);
  v_tables t_list := t_list(
    'RD_STATION_DASHBOARD_ORDERS','RD_STATION_MEALS_INVENTORY','RD_STATION_PROFILE','RD_STATION_SUBMISSIONS',
    'RD_PAYOUTS','RD_REDEMPTIONS','RD_REWARDS','RD_WALLET_LEDGER','RD_WALLETS','RD_MEAL_ORDERS','RD_MEALS',
    'RD_BOOKING_TYPES','RD_PLANS','RD_SETTINGS');
BEGIN
  FOR i IN 1 .. v_tables.COUNT LOOP
    BEGIN
      EXECUTE IMMEDIATE 'DROP TABLE ' || v_tables(i) || ' CASCADE CONSTRAINTS PURGE';
    EXCEPTION WHEN OTHERS THEN
      IF SQLCODE != -942 THEN RAISE; END IF;
    END;
  END LOOP;
END;
/

