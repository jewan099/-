-- شاشة "إضافة محطة جديدة" (طلبات المراجعة)
CREATE TABLE rd_station_submissions (
  submission_id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id                NUMBER NOT NULL REFERENCES rd_users(user_id) ON DELETE CASCADE,
  station_name            VARCHAR2(150) NOT NULL,
  city                    VARCHAR2(100) NOT NULL,
  highway_name            VARCHAR2(150) NOT NULL,
  description             VARCHAR2(2000),
  bus_capacity            NUMBER DEFAULT 30   NOT NULL,        -- سعة مواقف الحافلات الكبرى
  guest_capacity          NUMBER DEFAULT 1500 NOT NULL,        -- سعة صالات الضيافة والانتظار
  latitude                NUMBER(10,8) DEFAULT 24.32980000,    -- 24.3298 N
  longitude               NUMBER(11,8) DEFAULT 39.54110000,    -- 39.5411 E
  open_time               VARCHAR2(20) DEFAULT '24/7' NOT NULL,
  annual_subscription_fee NUMBER(10,2) DEFAULT 5000.00,        -- 5,000 ر.س
  station_share_percent   NUMBER DEFAULT 85,                   -- نسبة المالك 85%
  platform_share_percent  NUMBER DEFAULT 15,                   -- نسبة المنصة 15%
  status                  VARCHAR2(50) DEFAULT 'قيد المراجعة',
  created_at              TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- طلبات لوحة إدارة المحطة
CREATE TABLE rd_station_dashboard_orders (
  order_id               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_code             VARCHAR2(50)  NOT NULL,               -- مثل #ORD-8821
  rest_stop_id           NUMBER REFERENCES rd_rest_stops(rest_stop_id) ON DELETE CASCADE,
  campaign_name          VARCHAR2(150) NOT NULL,
  eta_minutes            NUMBER        NOT NULL,               -- الوقت المتبقي للوصول
  meal_count             NUMBER        NOT NULL,
  total_campaign_charge  NUMBER(10,2)  NOT NULL,               -- إجمالي الخصم من الحملة
  station_net_deposit    NUMBER(10,2)  NOT NULL,               -- إيداع محفظة المحطة 85%
  platform_fee_deducted  NUMBER(10,2)  NOT NULL,               -- رسوم المنصة 15%
  status                 VARCHAR2(50)  DEFAULT 'طلب جديد',
  created_at             TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- مخزون الوجبات بالمحطة
CREATE TABLE rd_station_meals_inventory (
  inventory_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rest_stop_id     NUMBER NOT NULL REFERENCES rd_rest_stops(rest_stop_id) ON DELETE CASCADE,
  meal_id          NUMBER REFERENCES rd_meals(meal_id),
  meal_title       VARCHAR2(100) NOT NULL,
  available_stock  NUMBER        NOT NULL,
  unit_price       NUMBER(10,2)  NOT NULL,
  updated_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- يقابل ON UPDATE CURRENT_TIMESTAMP في MySQL
CREATE OR REPLACE TRIGGER trg_rd_inventory_upd
BEFORE UPDATE ON rd_station_meals_inventory
FOR EACH ROW
BEGIN
  :NEW.updated_at := CURRENT_TIMESTAMP;
END;
/

