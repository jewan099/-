-- 3. توسيع الجداول الأساسية (يمكن إعادة تشغيله دون أخطاء)
--------------------------------------------------------------------------------
DECLARE
  v_cond VARCHAR2(32767);

  PROCEDURE run_sql(p_sql VARCHAR2, p_ignore NUMBER DEFAULT NULL) IS
  BEGIN
    EXECUTE IMMEDIATE p_sql;
  EXCEPTION WHEN OTHERS THEN
    IF p_ignore IS NULL OR SQLCODE != p_ignore THEN RAISE; END IF;
  END;

  PROCEDURE add_col(p_table VARCHAR2, p_col VARCHAR2, p_def VARCHAR2) IS
    v NUMBER;
  BEGIN
    SELECT COUNT(*) INTO v FROM user_tab_columns
     WHERE table_name = UPPER(p_table) AND column_name = UPPER(p_col);
    IF v = 0 THEN
      EXECUTE IMMEDIATE 'ALTER TABLE ' || p_table || ' ADD (' || p_col || ' ' || p_def || ')';
    END IF;
  END;

  PROCEDURE add_con(p_table VARCHAR2, p_name VARCHAR2, p_def VARCHAR2) IS
    v NUMBER;
  BEGIN
    SELECT COUNT(*) INTO v FROM user_constraints WHERE constraint_name = UPPER(p_name);
    IF v = 0 THEN
      EXECUTE IMMEDIATE 'ALTER TABLE ' || p_table || ' ADD CONSTRAINT ' || p_name || ' ' || p_def;
    END IF;
  END;
BEGIN
  ---------------- rd_users ----------------
  -- توسيع أنواع الحساب: السائق/المالك/المدير (الأساسية) + صاحب حملة/مستخدم (الموقع)
  FOR c IN (SELECT constraint_name, search_condition FROM user_constraints
             WHERE table_name = 'RD_USERS' AND constraint_type = 'C') LOOP
    v_cond := c.search_condition;
    IF UPPER(v_cond) LIKE '%USER_TYPE%' AND UPPER(v_cond) LIKE '%DRIVER%' THEN
      EXECUTE IMMEDIATE 'ALTER TABLE rd_users DROP CONSTRAINT ' || c.constraint_name;
    END IF;
  END LOOP;
  add_con('rd_users', 'ck_rd_users_type',
          'CHECK (user_type IN (''DRIVER'',''OWNER'',''ADMIN'',''CAMPAIGN'',''USER''))');
  run_sql('ALTER TABLE rd_users MODIFY (phone NULL)', -1451);   -- حسابات الموقع بلا جوال

  -- أعمدة الملف الشخصي (تأكيد وجودها كما في القاعدة الأساسية)
  add_col('rd_users', 'rating',                  'NUMBER(3,2) DEFAULT 5.00');
  add_col('rd_users', 'trips_count',             'NUMBER DEFAULT 0');
  add_col('rd_users', 'stations_count',          'NUMBER DEFAULT 0');
  add_col('rd_users', 'loyalty_points',          'NUMBER DEFAULT 0');
  add_col('rd_users', 'subscription_status',     'VARCHAR2(20) DEFAULT ''INACTIVE''');
  add_col('rd_users', 'subscription_expires_at', 'DATE');
  add_col('rd_users', 'wallet_balance',          'NUMBER(10,2) DEFAULT 0.00');
  add_col('rd_users', 'total_earnings',          'NUMBER(10,2) DEFAULT 0.00');

  ---------------- rd_rest_stops ----------------
  run_sql('ALTER TABLE rd_rest_stops MODIFY (owner_id NULL)', -1451);  -- محطات الموقع بلا مالك مسجّل

  add_col('rd_rest_stops', 'bus_capacity',         'NUMBER DEFAULT 0');
  add_col('rd_rest_stops', 'waiting_capacity',     'NUMBER DEFAULT 0');
  add_col('rd_rest_stops', 'open_time',            'VARCHAR2(10) DEFAULT ''24/7''');
  add_col('rd_rest_stops', 'contact_phone',        'VARCHAR2(20)');
  add_col('rd_rest_stops', 'congestion_level',     'VARCHAR2(20) DEFAULT ''LOW''');
  add_col('rd_rest_stops', 'occupancy_percentage', 'NUMBER(5,2) DEFAULT 0.00');
  add_col('rd_rest_stops', 'status',               'VARCHAR2(20) DEFAULT ''APPROVED''');
  -- من الموقع
  add_col('rd_rest_stops', 'area',          'VARCHAR2(150)');
  add_col('rd_rest_stops', 'is_visible',    'NUMBER(1) DEFAULT 1 NOT NULL CHECK (is_visible IN (0,1))');
  add_col('rd_rest_stops', 'plan_code',     'VARCHAR2(10) DEFAULT ''basic'' NOT NULL');
  add_col('rd_rest_stops', 'billing_cycle', 'VARCHAR2(8) DEFAULT ''MONTHLY'' NOT NULL');
  -- من التطبيق (جدول stations)
  add_col('rd_rest_stops', 'distance_km',         'NUMBER');
  add_col('rd_rest_stops', 'available_bus_slots', 'NUMBER');
  add_col('rd_rest_stops', 'rating',              'NUMBER(2,1)');

  add_con('rd_rest_stops', 'uq_rd_rest_stops_name',  'UNIQUE (name)');
  add_con('rd_rest_stops', 'fk_rd_stops_plan',       'FOREIGN KEY (plan_code) REFERENCES rd_plans(plan_code)');
  add_con('rd_rest_stops', 'ck_rd_stops_cycle',      'CHECK (billing_cycle IN (''MONTHLY'',''YEARLY''))');
  add_con('rd_rest_stops', 'ck_rd_stops_occupancy',  'CHECK (occupancy_percentage BETWEEN 0 AND 100)');

  ---------------- rd_bookings ----------------
  run_sql('ALTER TABLE rd_bookings MODIFY (driver_id NULL)', -1451);   -- حجوزات الموقع قد تكون لزائر
  run_sql('ALTER TABLE rd_bookings MODIFY (arrival_time VARCHAR2(30))'); -- "الآن" و "04:30 م"

  add_col('rd_bookings', 'bus_stop_bay',     'VARCHAR2(50)');
  add_col('rd_bookings', 'qr_code_token',    'VARCHAR2(100)');
  add_col('rd_bookings', 'total_amount',     'NUMBER(10,2) DEFAULT 0.00');
  add_col('rd_bookings', 'platform_fee',     'NUMBER(10,2) DEFAULT 0.00');
  add_col('rd_bookings', 'net_owner_amount', 'NUMBER(10,2) DEFAULT 0.00');
  -- من الموقع
  add_col('rd_bookings', 'booking_code',    'VARCHAR2(50)');
  add_col('rd_bookings', 'booking_type_id', 'NUMBER');
  add_col('rd_bookings', 'price',           'NUMBER(10,2)');
  add_col('rd_bookings', 'people_count',    'NUMBER(3) DEFAULT 1');
  -- من التطبيق (bookings / my_bookings)
  add_col('rd_bookings', 'pilgrim_count',         'NUMBER');
  add_col('rd_bookings', 'stop_duration_minutes', 'NUMBER');
  add_col('rd_bookings', 'meals_count',           'NUMBER');

  add_con('rd_bookings', 'uq_rd_bookings_code', 'UNIQUE (booking_code)');
  add_con('rd_bookings', 'fk_rd_bk_type',       'FOREIGN KEY (booking_type_id) REFERENCES rd_booking_types(booking_type_id)');

  ---------------- rd_reviews ----------------
  run_sql('ALTER TABLE rd_reviews MODIFY (driver_id NULL)', -1451);    -- تعليقات الزوار
  add_col('rd_reviews', 'reviewer_name', 'VARCHAR2(60) DEFAULT ''ضيف راحة'' NOT NULL');
END;
/

