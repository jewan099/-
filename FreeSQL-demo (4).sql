-- طلب وجبات من صاحب حملة: عملية واحدة (خصم المحفظة + قيد + الطلب)
CREATE OR REPLACE PROCEDURE sp_place_meal_order(
  p_campaign_id IN  NUMBER,
  p_station_id  IN  NUMBER,
  p_meal_id     IN  NUMBER,
  p_quantity    IN  NUMBER,
  p_code        OUT VARCHAR2
) IS
  v_price   NUMBER;
  v_name    VARCHAR2(100);
  v_total   NUMBER;
  v_balance NUMBER;
  v_has     NUMBER;
BEGIN
  IF NVL(p_quantity, 0) <= 0 THEN
    RAISE_APPLICATION_ERROR(-20030, 'أدخل عددًا صحيحًا');
  END IF;

  -- المحطة يجب أن يكون فيها مطعم
  SELECT COUNT(*) INTO v_has
    FROM rd_rest_stop_services ss JOIN rd_services sv ON sv.service_id = ss.service_id
   WHERE ss.rest_stop_id = p_station_id AND sv.service_name = 'مطعم';
  IF v_has = 0 THEN
    RAISE_APPLICATION_ERROR(-20031, 'هذه المحطة لا يوجد فيها مطعم');
  END IF;

  SELECT price, meal_name INTO v_price, v_name FROM rd_meals WHERE meal_id = p_meal_id AND is_active = 1;
  v_total := v_price * p_quantity;

  SELECT balance INTO v_balance FROM rd_wallets WHERE user_id = p_campaign_id FOR UPDATE;
  IF v_total > v_balance THEN
    RAISE_APPLICATION_ERROR(-20032, 'الرصيد غير كافٍ لهذا الطلب');
  END IF;

  p_code := 'O-' || TO_CHAR(TRUNC(DBMS_RANDOM.VALUE(10000, 99999)));

  UPDATE rd_wallets SET balance = balance - v_total WHERE user_id = p_campaign_id;
  UPDATE rd_users   SET wallet_balance = NVL(wallet_balance, 0) - v_total WHERE user_id = p_campaign_id;
  INSERT INTO rd_wallet_ledger (user_id, amount, reason, ref_code)
  VALUES (p_campaign_id, -v_total, 'طلب وجبات: ' || v_name || ' × ' || p_quantity, p_code);
  INSERT INTO rd_meal_orders (order_code, campaign_id, rest_stop_id, meal_id, meal_name, quantity, total, status)
  VALUES (p_code, p_campaign_id, p_station_id, p_meal_id, v_name, p_quantity, v_total, 'PAID');
  COMMIT;
END;
/

-- الإدارة: نقل الطلب مدفوع ← قيد التجهيز ← تم التسليم
CREATE OR REPLACE PROCEDURE sp_advance_order(p_order_id IN NUMBER) IS
BEGIN
  UPDATE rd_meal_orders
     SET status = CASE status WHEN 'PAID' THEN 'PREPARING' ELSE 'DELIVERED' END
   WHERE order_id = p_order_id AND status <> 'DELIVERED';
  COMMIT;
END;
