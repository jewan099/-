-- 1. حذف بيانات القاعدة الأساسية (من الأبناء إلى الآباء)
--------------------------------------------------------------------------------
DECLARE
  TYPE t_list IS TABLE OF VARCHAR2(40);
  v_tables t_list := t_list(
    'RD_MAINTENANCE_REPORTS','RD_LOYALTY_REWARDS','RD_TRANSACTIONS','RD_REST_STOP_IMAGES',
    'RD_REVIEWS','RD_BOOKINGS','RD_REST_STOP_SERVICES','RD_REST_STOPS','RD_SERVICES','RD_USERS');
BEGIN
  FOR i IN 1 .. v_tables.COUNT LOOP
    BEGIN
      EXECUTE IMMEDIATE 'DELETE FROM ' || v_tables(i);
      DBMS_OUTPUT.PUT_LINE('تم حذف ' || SQL%ROWCOUNT || ' صف من ' || v_tables(i));
    EXCEPTION WHEN OTHERS THEN
      IF SQLCODE != -942 THEN RAISE; END IF;
    END;
  END LOOP;
  COMMIT;
END;
/

-- إعادة ترقيم المعرّفات من 1 (إن لم تدعمها نسخة Oracle يستمر الترقيم فقط دون أي ضرر)
DECLARE
  PROCEDURE restart_id(p_table VARCHAR2, p_col VARCHAR2) IS
  BEGIN
    EXECUTE IMMEDIATE 'ALTER TABLE ' || p_table || ' MODIFY (' || p_col ||
                      ' GENERATED BY DEFAULT AS IDENTITY (RESTART START WITH 1))';
  EXCEPTION WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('تعذّر إعادة ترقيم ' || p_table || ' (' || SQLERRM || ')');
  END;
BEGIN
  restart_id('rd_users',               'user_id');
  restart_id('rd_rest_stops',          'rest_stop_id');
  restart_id('rd_services',            'service_id');
  restart_id('rd_bookings',            'booking_id');
  restart_id('rd_reviews',             'review_id');
  restart_id('rd_rest_stop_images',    'image_id');
  restart_id('rd_transactions',        'transaction_id');
  restart_id('rd_loyalty_rewards',     'reward_id');
  restart_id('rd_maintenance_reports', 'report_id');
END;
