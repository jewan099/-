SELECT s.rest_stop_id, s.name, s.city, s.highway_name AS area,
       s.occupancy_percentage AS crowd_percent, s.latitude, s.longitude,
       CASE WHEN s.occupancy_percentage < 40 THEN 'خفيف'
            WHEN s.occupancy_percentage < 75 THEN 'متوسط'
            ELSE 'مزدحم' END AS crowd_label,
       p.plan_name, p.plan_rank,
       (SELECT ROUND(AVG(r.rating), 1) FROM rd_reviews r WHERE r.rest_stop_id = s.rest_stop_id) AS rating,
       (SELECT COUNT(*) FROM rd_reviews r WHERE r.rest_stop_id = s.rest_stop_id)                AS reviews_count,
       (SELECT LISTAGG(sv.service_name, '، ') WITHIN GROUP (ORDER BY sv.service_id)
          FROM rd_rest_stop_services ss
          JOIN rd_services sv ON sv.service_id = ss.service_id
         WHERE ss.rest_stop_id = s.rest_stop_id) AS services,
       CASE WHEN EXISTS (SELECT 1 FROM rd_rest_stop_services ss
                           JOIN rd_services sv ON sv.service_id = ss.service_id
                          WHERE ss.rest_stop_id = s.rest_stop_id
                            AND sv.service_name IN ('مطعم', 'مطاعم'))
            THEN 1 ELSE 0 END AS has_meals
  FROM rd_rest_stops s
  LEFT JOIN rd_plans p ON p.plan_code = s.plan_code
 WHERE s.is_visible = 1;

