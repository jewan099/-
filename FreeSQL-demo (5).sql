  (SELECT COUNT(*) FROM rd_users WHERE user_type <> 'ADMIN')       AS accounts_count,
  (SELECT COUNT(*) FROM rd_payouts WHERE status = 'PENDING')       AS pending_payouts
  FROM dual;

