-- لوحة صاحب المحطة: الحجوزات والعمولة والصافي
CREATE OR REPLACE VIEW rd_v_station_dashboard AS
SELECT s.rest_stop_id, s.name,
       (SELECT COUNT(*) FROM rd_bookings b
         WHERE b.rest_stop_id = s.rest_stop_id AND b.status = 'confirmed') AS bookings_count,
       (SELECT NVL(SUM(b.total_amount), 0) FROM rd_bookings b
         WHERE b.rest_stop_id = s.rest_stop_id AND b.status = 'confirmed') AS bookings_total,
       ROUND((SELECT NVL(SUM(b.total_amount), 0) FROM rd_bookings b
               WHERE b.rest_stop_id = s.rest_stop_id AND b.status = 'confirmed')
             * fn_setting('BOOKING_COMMISSION_PCT') / 100, 2) AS platform_commission,
       ROUND((SELECT NVL(SUM(b.total_amount), 0) FROM rd_bookings b
               WHERE b.rest_stop_id = s.rest_stop_id AND b.status = 'confirmed')
             * (1 - fn_setting('BOOKING_COMMISSION_PCT') / 100), 2) AS station_net,
       CASE s.billing_cycle WHEN 'YEARLY' THEN p.yearly_price ELSE p.monthly_price END AS subscription_fee
  FROM rd_rest_stops s
  LEFT JOIN rd_plans p ON p.plan_code = s.plan_code;

-- نظرة المدير العامة على الإيرادات
CREATE OR REPLACE VIEW rd_v_admin_overview AS
