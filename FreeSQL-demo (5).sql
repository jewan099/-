CREATE TABLE rd_users (
    user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR2(100) NOT NULL,
    email VARCHAR2(100) UNIQUE NOT NULL,
    password VARCHAR2(255) NOT NULL,
    phone VARCHAR2(20) NOT NULL,
    user_type VARCHAR2(20) DEFAULT 'DRIVER' CHECK (user_type IN ('DRIVER', 'OWNER', 'ADMIN')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE rd_rest_stops (
    rest_stop_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id NUMBER NOT NULL,
    name VARCHAR2(150) NOT NULL,
    city VARCHAR2(100) NOT NULL,
    highway_name VARCHAR2(150),
    latitude NUMBER(10, 8),
    longitude NUMBER(11, 8),
    description VARCHAR2(1000),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_rd_stops_owner FOREIGN KEY (owner_id) REFERENCES rd_users(user_id) ON DELETE CASCADE
);

CREATE TABLE rd_services (
    service_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_name VARCHAR2(100) UNIQUE NOT NULL,
    description VARCHAR2(255)
);

CREATE TABLE rd_rest_stop_services (
    rest_stop_id NUMBER NOT NULL,
    service_id NUMBER NOT NULL,
    PRIMARY KEY (rest_stop_id, service_id),
    CONSTRAINT fk_rd_rss_stop FOREIGN KEY (rest_stop_id) REFERENCES rd_rest_stops(rest_stop_id) ON DELETE CASCADE,
    CONSTRAINT fk_rd_rss_service FOREIGN KEY (service_id) REFERENCES rd_services(service_id) ON DELETE CASCADE
);

CREATE TABLE rd_bookings (
    booking_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    driver_id NUMBER NOT NULL,
    rest_stop_id NUMBER NOT NULL,
    booking_date DATE NOT NULL,
    arrival_time VARCHAR2(10) NOT NULL,
    bus_count NUMBER DEFAULT 1 NOT NULL,
    status VARCHAR2(20) DEFAULT 'pending' CHECK (status IN ('pending', 'confirmed', 'completed', 'cancelled')),
    notes VARCHAR2(1000),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_rd_bk_driver FOREIGN KEY (driver_id) REFERENCES rd_users(user_id) ON DELETE CASCADE,
    CONSTRAINT fk_rd_bk_stop FOREIGN KEY (rest_stop_id) REFERENCES rd_rest_stops(rest_stop_id) ON DELETE CASCADE
);

CREATE TABLE rd_reviews (
    review_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    driver_id NUMBER NOT NULL,
    rest_stop_id NUMBER NOT NULL,
    rating NUMBER(1) CHECK (rating BETWEEN 1 AND 5) NOT NULL,
    comment_text VARCHAR2(1000),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_rd_rev_driver FOREIGN KEY (driver_id) REFERENCES rd_users(user_id) ON DELETE CASCADE,
    CONSTRAINT fk_rd_rev_stop FOREIGN KEY (rest_stop_id) REFERENCES rd_rest_stops(rest_stop_id) ON DELETE CASCADE
);

