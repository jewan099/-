CREATE OR REPLACE PROCEDURE sp_approve_payout(p_payout_id IN NUMBER) IS
BEGIN
  UPDATE rd_payouts SET status = 'PAID' WHERE payout_id = p_payout_id AND status = 'PENDING';
  COMMIT;
END;
