-- استبدال نقاط بمكافأة
CREATE OR REPLACE PROCEDURE sp_redeem_reward(
  p_user_id   IN  NUMBER,
  p_reward_id IN  NUMBER,
  p_code      OUT VARCHAR2
) IS
  v_cost  NUMBER;
  v_title VARCHAR2(100 CHAR);
  v_pts   NUMBER;
BEGIN
  SELECT cost_points, title INTO v_cost, v_title FROM rd_rewards WHERE reward_id = p_reward_id;
  SELECT loyalty_points INTO v_pts FROM rd_users WHERE user_id = p_user_id FOR UPDATE;

  IF v_pts < v_cost THEN
    RAISE_APPLICATION_ERROR(-20020, 'رصيد النقاط غير كافٍ');
  END IF;

  p_code := 'RW-' || TO_CHAR(TRUNC(DBMS_RANDOM.VALUE(10000, 99999)));
  UPDATE rd_users SET loyalty_points = loyalty_points - v_cost WHERE user_id = p_user_id;
  INSERT INTO rd_redemptions (user_id, reward_id, voucher_code) VALUES (p_user_id, p_reward_id, p_code);
  INSERT INTO rd_loyalty_rewards (user_id, action_type, points, reward_description)
  VALUES (p_user_id, 'REDEEM', -v_cost, v_title);
  COMMIT;
END;
/

-- طلب وجبات من صاحب حملة (خصم من المحفظة + قيد + الطلب + المعاملة المالية)
CREATE OR REPLACE PROCEDURE sp_place_meal_order(
  p_campaign_id  IN  NUMBER,
  p_rest_stop_id IN  NUMBER,
  p_meal_id      IN  NUMBER,
  p_quantity     IN  NUMBER,
  p_code         OUT VARCHAR2
) IS
  v_price    NUMBER;
  v_name     VARCHAR2(100 CHAR);
  v_total    NUMBER;
  v_balance  NUMBER;
  v_has      NUMBER;
  v_owner    NUMBER;
  v_pct      NUMBER;
  v_fee      NUMBER;
  v_order_id NUMBER;
BEGIN
  IF NVL(p_quantity, 0) <= 0 THEN
    RAISE_APPLICATION_ERROR(-20030, 'أدخل عددًا صحيحًا');
  END IF;

  SELECT COUNT(*) INTO v_has
    FROM rd_rest_stop_services ss JOIN rd_services sv ON sv.service_id = ss.service_id
   WHERE ss.rest_stop_id = p_rest_stop_id AND sv.service_name IN ('مطعم', 'مطاعم');
  IF v_has = 0 THEN
    RAISE_APPLICATION_ERROR(-20031, 'هذه المحطة لا يوجد فيها مطعم');
  END IF;

  SELECT price, meal_name INTO v_price, v_name FROM rd_meals WHERE meal_id = p_meal_id AND is_active = 1;
  v_total := v_price * p_quantity;

  SELECT wallet_balance INTO v_balance FROM rd_users WHERE user_id = p_campaign_id FOR UPDATE;
  IF v_total > v_balance THEN
    RAISE_APPLICATION_ERROR(-20032, 'الرصيد غير كافٍ لهذا الطلب');
  END IF;

  SELECT owner_id INTO v_owner FROM rd_rest_stops WHERE rest_stop_id = p_rest_stop_id;
  v_pct := fn_setting('MEAL_COMMISSION_PCT');
  v_fee := ROUND(v_total * v_pct / 100, 2);
  p_code := 'O-' || TO_CHAR(TRUNC(DBMS_RANDOM.VALUE(10000, 99999)));

  UPDATE rd_users SET wallet_balance = wallet_balance - v_total WHERE user_id = p_campaign_id;
  INSERT INTO rd_wallet_ledger (user_id, amount, reason, ref_code)
  VALUES (p_campaign_id, -v_total, 'طلب وجبات: ' || v_name || ' × ' || p_quantity, p_code);

  INSERT INTO rd_meal_orders (order_code, campaign_id, rest_stop_id, meal_id, meal_name, quantity, total, status)
  VALUES (p_code, p_campaign_id, p_rest_stop_id, p_meal_id, v_name, p_quantity, v_total, 'PAID')
  RETURNING order_id INTO v_order_id;

  INSERT INTO rd_transactions (order_id, campaign_owner_id, rest_stop_owner_id, total_amount,
                               platform_percentage, platform_profit, owner_payout, transaction_type)
  VALUES (v_order_id, p_campaign_id, v_owner, v_total, v_pct, v_fee, v_total - v_fee, 'MEAL');
  COMMIT;
END;
/

-- الإدارة: نقل الطلب مدفوع ← قيد التجهيز ← تم التسليم
CREATE OR REPLACE PROCEDURE sp_advance_order(p_order_id IN NUMBER) IS
BEGIN
  UPDATE rd_meal_orders
     SET status = CASE status WHEN 'PAID' THEN 'PREPARING' ELSE 'DELIVERED' END
   WHERE order_id = p_order_id AND status <> 'DELIVERED';
  COMMIT;
END;
