-- تعديل وحذف طلبات الوجبات (الفرق يُخصم أو يُرد للمحفظة إذا كان الطلب مدفوعًا منها)
--------------------------------------------------------------------------------

CREATE OR REPLACE PROCEDURE sp_update_meal_order(p_code IN VARCHAR2, p_quantity IN NUMBER) IS
  v_order rd_meal_orders%ROWTYPE;
  v_price NUMBER;
  v_new   NUMBER;
  v_paid  NUMBER;
  v_diff  NUMBER;
  v_bal   NUMBER;
  v_pct   NUMBER;
  v_fee   NUMBER;
BEGIN
  IF NVL(p_quantity, 0) <= 0 THEN
    RAISE_APPLICATION_ERROR(-20060, 'أدخل عددًا صحيحًا');
  END IF;

  BEGIN
    SELECT * INTO v_order FROM rd_meal_orders WHERE order_code = p_code FOR UPDATE;
  EXCEPTION WHEN NO_DATA_FOUND THEN
    RAISE_APPLICATION_ERROR(-20061, 'الطلب غير موجود');
  END;

  IF v_order.status = 'DELIVERED' THEN
    RAISE_APPLICATION_ERROR(-20062, 'لا يمكن تعديل طلب تم تسليمه');
  END IF;

  SELECT price INTO v_price FROM rd_meals WHERE meal_id = v_order.meal_id;
  v_new := v_price * p_quantity;

  SELECT NVL(-SUM(amount), 0) INTO v_paid FROM rd_wallet_ledger WHERE ref_code = p_code;
  IF v_paid > 0 THEN
    v_diff := v_new - v_paid;
    IF v_diff <> 0 THEN
      SELECT wallet_balance INTO v_bal FROM rd_users WHERE user_id = v_order.campaign_id FOR UPDATE;
      IF v_diff > v_bal THEN
        RAISE_APPLICATION_ERROR(-20063, 'الرصيد غير كافٍ لهذا التعديل');
      END IF;
      UPDATE rd_users SET wallet_balance = wallet_balance - v_diff WHERE user_id = v_order.campaign_id;
      INSERT INTO rd_wallet_ledger (user_id, amount, reason, ref_code)
      VALUES (v_order.campaign_id, -v_diff, 'تعديل طلب وجبات', p_code);
    END IF;
  END IF;

  UPDATE rd_meal_orders SET quantity = p_quantity, total = v_new WHERE order_id = v_order.order_id;

  v_pct := fn_setting('MEAL_COMMISSION_PCT');
  v_fee := ROUND(v_new * v_pct / 100, 2);
  UPDATE rd_transactions
     SET total_amount = v_new, platform_percentage = v_pct,
         platform_profit = v_fee, owner_payout = v_new - v_fee
   WHERE order_id = v_order.order_id;
  COMMIT;
END;
/

CREATE OR REPLACE PROCEDURE sp_delete_meal_order(p_code IN VARCHAR2) IS
  v_id       NUMBER;
  v_campaign NUMBER;
  v_status   VARCHAR2(10);
  v_paid     NUMBER;
BEGIN
  BEGIN
    SELECT order_id, campaign_id, status INTO v_id, v_campaign, v_status
      FROM rd_meal_orders WHERE order_code = p_code FOR UPDATE;
  EXCEPTION WHEN NO_DATA_FOUND THEN
    RAISE_APPLICATION_ERROR(-20061, 'الطلب غير موجود');
  END;

  IF v_status = 'DELIVERED' THEN
    RAISE_APPLICATION_ERROR(-20064, 'لا يمكن حذف طلب تم تسليمه');
  END IF;

  SELECT NVL(-SUM(amount), 0) INTO v_paid FROM rd_wallet_ledger WHERE ref_code = p_code;
  IF v_paid > 0 THEN
    UPDATE rd_users SET wallet_balance = wallet_balance + v_paid WHERE user_id = v_campaign;
    INSERT INTO rd_wallet_ledger (user_id, amount, reason, ref_code)
    VALUES (v_campaign, v_paid, 'إلغاء طلب وجبات', p_code);
  END IF;

  DELETE FROM rd_meal_orders WHERE order_id = v_id;
  COMMIT;
END;
/

-- الضيف يختار يبي وجبة الحملة أو لا (1 = يبي، 0 = ما يبي)
CREATE OR REPLACE PROCEDURE sp_respond_meal_order(
  p_order_id IN NUMBER,
  p_user_id  IN NUMBER,
  p_wants    IN NUMBER
) IS
  v_wants NUMBER := CASE WHEN NVL(p_wants, 0) = 1 THEN 1 ELSE 0 END;
BEGIN
  MERGE INTO rd_meal_order_responses r
  USING (SELECT p_order_id AS oid, p_user_id AS uid FROM dual) s
     ON (r.order_id = s.oid AND r.user_id = s.uid)
  WHEN MATCHED THEN
    UPDATE SET r.wants_meal = v_wants, r.updated_at = SYSTIMESTAMP
  WHEN NOT MATCHED THEN
    INSERT (order_id, user_id, wants_meal) VALUES (s.oid, s.uid, v_wants);
  COMMIT;
END;
