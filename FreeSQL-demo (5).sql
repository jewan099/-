-- تسجيل الدخول وإنشاء الحساب (كلمة المرور تُخزَّن SHA256 بأحرف صغيرة، مثل SHA2 في MySQL)
--------------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION fn_login(p_email VARCHAR2, p_password VARCHAR2) RETURN NUMBER IS
  v_id NUMBER;
BEGIN
  SELECT user_id INTO v_id FROM rd_users
   WHERE email = p_email
     AND password = LOWER(RAWTOHEX(STANDARD_HASH(p_password, 'SHA256')));
  RETURN v_id;
EXCEPTION WHEN NO_DATA_FOUND THEN
  RETURN NULL;
END;
/

CREATE OR REPLACE PROCEDURE sp_register_user(
  p_type     IN  VARCHAR2,
  p_name     IN  VARCHAR2,
  p_email    IN  VARCHAR2,
  p_phone    IN  VARCHAR2,
  p_password IN  VARCHAR2,
  p_user_id  OUT NUMBER
) IS
BEGIN
  IF p_type NOT IN ('USER', 'CAMPAIGN', 'OWNER') THEN
    RAISE_APPLICATION_ERROR(-20050, 'نوع الحساب غير صحيح');
  END IF;
  IF p_password IS NULL OR LENGTH(p_password) < 4 THEN
    RAISE_APPLICATION_ERROR(-20051, 'كلمة المرور قصيرة');
  END IF;

  BEGIN
    INSERT INTO rd_users (full_name, email, password, phone, user_type, wallet_balance)
    VALUES (p_name, p_email, LOWER(RAWTOHEX(STANDARD_HASH(p_password, 'SHA256'))), p_phone, p_type,
            CASE WHEN p_type = 'CAMPAIGN' THEN 10000 ELSE 0 END)
    RETURNING user_id INTO p_user_id;
  EXCEPTION WHEN DUP_VAL_ON_INDEX THEN
    RAISE_APPLICATION_ERROR(-20052, 'البريد مسجل مسبقًا');
  END;

  IF p_type = 'USER' THEN
    INSERT INTO rd_guest_profiles (user_id) VALUES (p_user_id);
  ELSIF p_type = 'CAMPAIGN' THEN
    INSERT INTO rd_campaign_profiles (user_id) VALUES (p_user_id);
    INSERT INTO rd_wallet_ledger (user_id, amount, reason, ref_code)
    VALUES (p_user_id, 10000, 'رصيد افتتاحي تجريبي', 'OPENING');
  END IF;
  COMMIT;
END;
/

