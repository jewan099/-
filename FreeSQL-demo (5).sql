-- أداة مساعدة: تنفّذ أمر DDL وتتجاهل خطأ "موجود مسبقًا"
CREATE OR REPLACE PROCEDURE sp_ddl_safe(p_sql IN VARCHAR2) AUTHID CURRENT_USER IS
BEGIN
  EXECUTE IMMEDIATE p_sql;
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE NOT IN (-955, -1430, -2260, -2261, -2264, -2275, -1408, -2299) THEN
    RAISE;
  END IF;
END;
