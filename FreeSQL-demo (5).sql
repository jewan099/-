-- تأكيد حجز (+50 نقطة)
CREATE OR REPLACE PROCEDURE sp_confirm_booking(
  p_user_id         IN  NUMBER,
  p_rest_stop_id    IN  NUMBER,
  p_booking_type_id IN  NUMBER,
  p_arrival_time    IN  VARCHAR2,
  p_people          IN  NUMBER,
  p_code            OUT VARCHAR2
) IS
  v_price      NUMBER;
  v_owner      NUMBER;
  v_pct        NUMBER;
  v_fee        NUMBER;
  v_booking_id NUMBER;
BEGIN
  BEGIN
    SELECT bt.price, s.owner_id INTO v_price, v_owner
      FROM rd_booking_types bt
      JOIN rd_rest_stop_services ss ON ss.service_id = bt.service_id
      JOIN rd_rest_stops s          ON s.rest_stop_id = ss.rest_stop_id
     WHERE bt.booking_type_id = p_booking_type_id
       AND ss.rest_stop_id    = p_rest_stop_id
       AND s.is_visible = 1;
  EXCEPTION WHEN NO_DATA_FOUND THEN
    RAISE_APPLICATION_ERROR(-20001, 'هذه الخدمة غير متوفرة في المحطة المختارة');
  END;

  v_pct := fn_setting('BOOKING_COMMISSION_PCT');
  v_fee := ROUND(v_price * v_pct / 100, 2);
  p_code := 'RD-' || TO_CHAR(TRUNC(DBMS_RANDOM.VALUE(10000, 99999)));

  INSERT INTO rd_bookings (driver_id, rest_stop_id, booking_date, arrival_time, bus_count, status,
                           booking_code, booking_type_id, people_count, qr_code_token,
                           total_amount, platform_fee, net_owner_amount)
  VALUES (p_user_id, p_rest_stop_id, TRUNC(SYSDATE), NVL(p_arrival_time, 'الآن'), 1, 'confirmed',
          p_code, p_booking_type_id, NVL(p_people, 1), p_code || '-' || RAWTOHEX(SYS_GUID()),
          v_price, v_fee, v_price - v_fee)
  RETURNING booking_id INTO v_booking_id;

  INSERT INTO rd_transactions (booking_id, campaign_owner_id, rest_stop_owner_id, total_amount,
                               platform_percentage, platform_profit, owner_payout, transaction_type)
  VALUES (v_booking_id, p_user_id, v_owner, v_price, v_pct, v_fee, v_price - v_fee, 'BOOKING');

  IF p_user_id IS NOT NULL THEN
    UPDATE rd_users SET loyalty_points = loyalty_points + 50, trips_count = trips_count + 1
     WHERE user_id = p_user_id;
    INSERT INTO rd_loyalty_rewards (user_id, action_type, points, reward_description)
    VALUES (p_user_id, 'BOOKING', 50, 'تأكيد حجز ' || p_code);
  END IF;
  COMMIT;
END;
/

-- إضافة تقييم وتعليق (+10 نقاط) ويحدّث متوسط تقييم المحطة
CREATE OR REPLACE PROCEDURE sp_add_review(
  p_user_id      IN NUMBER,
  p_rest_stop_id IN NUMBER,
  p_name         IN VARCHAR2,
  p_rating       IN NUMBER,
  p_comment      IN VARCHAR2
) IS
BEGIN
  IF p_comment IS NULL OR LENGTH(TRIM(p_comment)) = 0 THEN
    RAISE_APPLICATION_ERROR(-20010, 'اكتب تعليقك أولًا');
  END IF;

  INSERT INTO rd_reviews (driver_id, rest_stop_id, reviewer_name, rating, comment_text)
  VALUES (p_user_id, p_rest_stop_id, NVL(TRIM(p_name), 'ضيف راحة'), p_rating, SUBSTR(p_comment, 1, 300));

  UPDATE rd_rest_stops
     SET avg_rating = (SELECT ROUND(AVG(rating), 1) FROM rd_reviews WHERE rest_stop_id = p_rest_stop_id)
   WHERE rest_stop_id = p_rest_stop_id;

  IF p_user_id IS NOT NULL THEN
    UPDATE rd_users SET loyalty_points = loyalty_points + 10 WHERE user_id = p_user_id;
    INSERT INTO rd_loyalty_rewards (user_id, action_type, points, reward_description)
    VALUES (p_user_id, 'REVIEW', 10, 'تقييم محطة');
  END IF;
  COMMIT;
END;
