-- 1) برنامج الولاء والنقاط (المكافآت كما في صفحة الموقع)
CREATE TABLE rd_customer_rewards (
  reward_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_points NUMBER DEFAULT 0 NOT NULL,                 -- رصيد نقاط العميل الافتراضي
  reward_type     VARCHAR2(50)  NOT NULL,                    -- meal | fuel | station
  reward_title    VARCHAR2(100 CHAR) NOT NULL,
  discount_value  NUMBER(10,2),                              -- قيمة الخصم بالريال (فاضية لو غير محددة)
  points_required NUMBER NOT NULL,                           -- النقاط المطلوبة للاستبدال
  is_active       NUMBER(1) DEFAULT 1 NOT NULL CHECK (is_active IN (0,1)),
  created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2) إعدادات الخريطة والتصفية الافتراضية
CREATE TABLE rd_map_settings (
  setting_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  default_latitude  NUMBER(10,8) DEFAULT 21.38910000,        -- مكة
  default_longitude NUMBER(11,8) DEFAULT 39.85790000,
  zoom_level        NUMBER DEFAULT 11 NOT NULL,
  default_filter    VARCHAR2(50) DEFAULT 'all',              -- all | new | old
  updated_at        TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Oracle ما فيه ON UPDATE، فنحدّث وقت التعديل بمشغّل (Trigger)
CREATE OR REPLACE TRIGGER trg_rd_map_settings_upd
BEFORE UPDATE ON rd_map_settings
FOR EACH ROW
BEGIN
  :NEW.updated_at := SYSTIMESTAMP;
END;
/

-- 3) أرقام الطوارئ والخدمات المساندة
CREATE TABLE rd_emergency_contacts (
  emergency_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  service_name        VARCHAR2(100 CHAR) NOT NULL,
  phone_number        VARCHAR2(20) NOT NULL,
  service_description VARCHAR2(1000 CHAR),
  display_order       NUMBER DEFAULT 1 NOT NULL,
  created_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 4) معلومات الإصدار والبناء للتطبيق
CREATE TABLE rd_app_version_info (
  version_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  app_name           VARCHAR2(100 CHAR) DEFAULT 'راحة ضيف' NOT NULL,
  version_number     VARCHAR2(20) DEFAULT 'v2.4' NOT NULL,
  build_number       NUMBER DEFAULT 104 NOT NULL,
  max_text_length    NUMBER DEFAULT 300 NOT NULL,            -- حد أحرف نموذج البلاغات
  max_upload_size_mb NUMBER DEFAULT 10 NOT NULL,             -- حد حجم الملفات المرفوعة
  updated_at         TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

